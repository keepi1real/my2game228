'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),{execFileSync}=require('child_process');
const root=path.resolve(__dirname,'..'),out=path.join(root,'dist/room-route');
fs.mkdirSync(out,{recursive:true});
execFileSync(process.execPath,[path.join(__dirname,'test-room-route.js')],{stdio:'inherit'});
execFileSync(process.execPath,[path.join(__dirname,'bundle.js'),'--room-route',path.join(out,'rogue-route-v1.html')],{stdio:'inherit'});
const html=fs.readFileSync(path.join(out,'rogue-route-v1.html'),'utf8');
const script=html.match(/<script>([\s\S]*)<\/script>/)[1];new vm.Script(script);
if(/(?:src|href)="(?:assets|js|css)\//.test(html)||/assets\/room-(?:visual|route)-v1\//.test(script))throw Error('Unbundled room resource');
execFileSync(process.execPath,[path.join(__dirname,'test-room-route-bundle.js')],{stdio:'inherit'});
const kit=path.join(out,'my2game228-route-v1');fs.mkdirSync(kit,{recursive:true});
for(const dir of ['assets','css','js','tools','tests','.github'])if(fs.existsSync(path.join(root,dir)))fs.cpSync(path.join(root,dir),path.join(kit,dir),{recursive:true});
for(const name of ['index.html','README.md','ROOM_ROUTE.md','ROOM_VISUAL.md','MOBILE.md','COOP.md','manifest.webmanifest','sw.js','.gitignore'])fs.copyFileSync(path.join(root,name),path.join(kit,name));
fs.copyFileSync(path.join(out,'rogue-route-v1.html'),path.join(kit,'play.html'));
const shots=fs.readdirSync(out).filter(n=>/^\d\d-.*\.png$/.test(n));fs.mkdirSync(path.join(kit,'screenshots'),{recursive:true});
for(const name of [...shots,'validation.json'])fs.copyFileSync(path.join(out,name),path.join(kit,'screenshots',name));
const zip=path.join(out,'rogue-route-v1.zip');if(fs.existsSync(zip))fs.unlinkSync(zip);
execFileSync('zip',['-q','-r',zip,path.basename(kit)],{cwd:out});
execFileSync('unzip',['-tq',zip],{stdio:'inherit'});
console.log('Ready: rogue-route-v1.html and rogue-route-v1.zip (full project + play.html).');
