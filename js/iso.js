'use strict';
// Изометрическая проекция 2:1.
//
// Мир остаётся плоским: сущности живут в тех же пиксельных координатах (x, y),
// что и раньше, столкновения, поиск пути и радиусы умений считаются по ним же.
// Проекция — целиком дело отрисовки и ввода: логика о ней не знает.
//
// Квадрат TILE×TILE ложится на экран ромбом шириной TILE и высотой TILE/2.

const ISO_KX = 0.5, ISO_KY = 0.25;

// Ромб вдвое ниже квадрата, поэтому в тот же экран влезает вдвое больше карты,
// чем при виде сверху, и фигуры теряются. Приближение возвращает прежний масштаб.
const ISO_ZOOM = 1.5;

// Высота стены на экране, в единицах до приближения. Примерно полтора ромба:
// выше — и стены съедают комнату, ниже — читаются как плоские заплатки.
const ISO_WALL_H = 26;

const isoX = (wx, wy) => (wx - wy) * ISO_KX;
const isoY = (wx, wy) => (wx + wy) * ISO_KY;

// Обратная проекция: точка экрана (уже без камеры и приближения) — в точку пола.
function isoToWorld(sx, sy) {
  return { x: sx / (2 * ISO_KX) + sy / (2 * ISO_KY), y: sy / (2 * ISO_KY) - sx / (2 * ISO_KX) };
}

// Направление с экрана в мир. Нужно для WASD: игрок ждёт, что W уведёт фигуру
// вверх по экрану, а не вдоль мировой оси Y, которая на экране идёт наискось.
function isoDir(sx, sy) {
  const w = isoToWorld(sx, sy), l = Math.hypot(w.x, w.y);
  return l > 0 ? { x: w.x / l, y: w.y / l } : { x: 0, y: 0 };
}

// Порядок отрисовки: чем больше сумма координат, тем ближе к зрителю и тем позже
// рисуется. Одинаково работает и для тайлов, и для сущностей между ними.
const isoDepth = (wx, wy) => wx + wy;

// Окружность в плоскости пола становится на экране эллипсом с осями в этих
// долях радиуса. Вывод: точка (R·cos t, R·sin t) проецируется в
// (√2·R·KX·cos(t+45°), √2·R·KY·sin(t+45°)) — то есть ровный эллипс, но угол
// вдоль него смещён на 45°.
const ISO_CIRCLE_X = Math.SQRT2 * ISO_KX;
const ISO_CIRCLE_Y = Math.SQRT2 * ISO_KY;
const ISO_ANGLE_SHIFT = Math.PI / 4;

// Угол направления на экране: по нему разворачиваются снаряды и оружие.
const isoAngle = (wx, wy) => Math.atan2(isoY(wx, wy), isoX(wx, wy));
